// Generate TypeScript types and standalone ajv validators for the agent trace
// models from the schema file that scripts/export_agent_schemas.py writes.
import { readFile, writeFile } from "node:fs/promises";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

// The models the browser reads directly; everything else is a shared definition.
const ROOTS = ["AgentTraceRecord", "AgentEvent"];
const BANNER = "// Generated by scripts/generate-agent-schemas.mjs. Do not edit.\n";

const generated = new URL("../src/generated/", import.meta.url);
const document = JSON.parse(await readFile(new URL("agentSchemas.json", generated), "utf8"));

// Pydantic titles every property, which would give each field its own named type.
const untitledProperties = JSON.parse(JSON.stringify(document.$defs), (key, value) => {
  if (value?.properties) {
    for (const field of Object.values(value.properties)) {
      delete field.title;
    }
  }
  return value;
});
const types = await compile(
  {
    title: "AgentSchemas",
    type: "object",
    properties: Object.fromEntries(ROOTS.map((name) => [name, { $ref: `#/$defs/${name}` }])),
    additionalProperties: false,
    $defs: untitledProperties,
  },
  "AgentSchemas",
  { bannerComment: "", additionalProperties: false },
);
await writeFile(new URL("agentSchemas.ts", generated), BANNER + types);

// ajv reads ``discriminator.propertyName`` but rejects OpenAPI's ``mapping``,
// and wants the union typed as an object. Each member pins ``kind`` with ``const``.
const forAjv = JSON.parse(JSON.stringify(document), (key, value) =>
  value?.discriminator
    ? {
        ...value,
        type: "object",
        discriminator: { propertyName: value.discriminator.propertyName },
      }
    : value,
);
const ajv = new Ajv2020({ code: { source: true, esm: true }, discriminator: true });
ajv.addSchema({ ...forAjv, $id: "agent" });
const validators = standaloneCode(
  ajv,
  Object.fromEntries(ROOTS.map((name) => [`validate${name}`, `agent#/$defs/${name}`])),
);
await writeFile(new URL("agentValidators.js", generated), BANNER + validators);
await writeFile(
  new URL("agentValidators.d.ts", generated),
  BANNER +
    'import type { ValidateFunction } from "ajv";\n\n' +
    `import type { ${ROOTS.join(", ")} } from "./agentSchemas";\n\n` +
    ROOTS.map((name) => `export const validate${name}: ValidateFunction<${name}>;\n`).join(""),
);

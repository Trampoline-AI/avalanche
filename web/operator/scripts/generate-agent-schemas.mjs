// Generate zod schemas and TypeScript types for the agent trace models from the
// schema file that scripts/export_agent_schemas.py writes.
//
// Only the JSON Schema keywords Pydantic emits for these models are supported;
// anything else fails generation instead of producing a looser schema.
import { readFile, writeFile } from "node:fs/promises";

const BANNER = "// Generated by scripts/generate-agent-schemas.mjs. Do not edit.\n";
// Annotations with no effect on validation.
const IGNORED = new Set(["title", "description", "default"]);

const generated = new URL("../src/generated/", import.meta.url);
const { $defs: defs } = JSON.parse(
  await readFile(new URL("agentSchemas.json", generated), "utf8"),
);

function refName(ref) {
  const name = ref.replace(/^#\/\$defs\//, "");
  if (name === ref || !(name in defs)) {
    throw new Error(`Unsupported $ref ${ref}`);
  }
  return name;
}

function checkKeys(schema, allowed) {
  for (const key of Object.keys(schema)) {
    if (!allowed.includes(key) && !IGNORED.has(key)) {
      throw new Error(`Unsupported JSON Schema keyword ${key} in ${JSON.stringify(schema)}`);
    }
  }
}

function bounds(schema) {
  let suffix = "";
  if ("minimum" in schema) suffix += `.min(${schema.minimum})`;
  if ("exclusiveMinimum" in schema) suffix += `.gt(${schema.exclusiveMinimum})`;
  return suffix;
}

function zod(schema, deps) {
  const keys = Object.keys(schema).filter((key) => !IGNORED.has(key));
  if (keys.length === 0) return "z.json()";
  if ("$ref" in schema) {
    checkKeys(schema, ["$ref"]);
    const name = refName(schema.$ref);
    deps.add(name);
    return name;
  }
  if ("const" in schema) {
    checkKeys(schema, ["const", "type"]);
    return `z.literal(${JSON.stringify(schema.const)})`;
  }
  if ("enum" in schema) {
    checkKeys(schema, ["enum", "type"]);
    return `z.enum(${JSON.stringify(schema.enum)})`;
  }
  if ("oneOf" in schema) {
    checkKeys(schema, ["oneOf", "discriminator"]);
    const members = schema.oneOf.map((member) => zod(member, deps)).join(", ");
    return `z.discriminatedUnion(${JSON.stringify(schema.discriminator.propertyName)}, [${members}])`;
  }
  if ("anyOf" in schema) {
    checkKeys(schema, ["anyOf"]);
    return `z.union([${schema.anyOf.map((member) => zod(member, deps)).join(", ")}])`;
  }
  switch (schema.type) {
    case "object": {
      checkKeys(schema, ["type", "properties", "required", "additionalProperties"]);
      if (!("properties" in schema) && typeof schema.additionalProperties === "object") {
        return `z.record(z.string(), ${zod(schema.additionalProperties, deps)})`;
      }
      if (schema.additionalProperties !== false) {
        throw new Error(`Object schemas must forbid extra fields: ${JSON.stringify(schema)}`);
      }
      const required = new Set(schema.required ?? []);
      const fields = Object.entries(schema.properties).map(([name, field]) => {
        const value = zod(field, deps);
        return `${JSON.stringify(name)}: ${required.has(name) ? value : `${value}.optional()`}`;
      });
      return `z.strictObject({ ${fields.join(", ")} })`;
    }
    case "array":
      checkKeys(schema, ["type", "items"]);
      return `z.array(${zod(schema.items, deps)})`;
    case "string":
      checkKeys(schema, ["type", "minLength"]);
      return "minLength" in schema ? `z.string().min(${schema.minLength})` : "z.string()";
    case "integer":
      checkKeys(schema, ["type", "minimum", "exclusiveMinimum"]);
      // z.int() accepts safe integers only; nanosecond timestamps exceed 2**53.
      return `z.number()${bounds(schema)}.refine(Number.isInteger, "Expected an integer")`;
    case "number":
      checkKeys(schema, ["type", "minimum", "exclusiveMinimum"]);
      return `z.number()${bounds(schema)}`;
    case "boolean":
      checkKeys(schema, ["type"]);
      return "z.boolean()";
    case "null":
      checkKeys(schema, ["type"]);
      return "z.null()";
    default:
      throw new Error(`Unsupported JSON Schema ${JSON.stringify(schema)}`);
  }
}

// Each definition becomes a named schema, emitted after the ones it references.
const built = new Map(
  Object.entries(defs).map(([name, schema]) => {
    const deps = new Set();
    return [name, { code: zod(schema, deps), deps }];
  }),
);
const ordered = [];
const visiting = new Set();
function visit(name) {
  if (ordered.includes(name)) return;
  if (visiting.has(name)) throw new Error(`Recursive schema ${name} is not supported`);
  visiting.add(name);
  for (const dep of built.get(name).deps) visit(dep);
  visiting.delete(name);
  ordered.push(name);
}
Object.keys(defs).sort().forEach(visit);

const body = ordered
  .map(
    (name) =>
      `export const ${name} = ${built.get(name).code};\n` +
      `export type ${name} = z.infer<typeof ${name}>;\n`,
  )
  .join("\n");
await writeFile(
  new URL("agentSchemas.ts", generated),
  `${BANNER}import { z } from "zod";\n\n${body}`,
);
